"""Greedy vs dynamic programming: solution quality and runtime.

Generates random stock universes and measures
  1. how often greedy is optimal, and its average / worst optimality gap
  2. how runtime grows with the budget W (DP is O(n·W), greedy is O(n log n))

Usage:
    python benchmarks/compare_algorithms.py

Writes results/benchmark_results.md and results/runtime_vs_budget.png.
"""

from __future__ import annotations

import random
import statistics
import sys
import time
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from simulator.optimization import dp_allocation, greedy_allocation  # noqa: E402

RESULTS = Path(__file__).resolve().parents[1] / "results"
SEED = 42


def random_universe(rng: random.Random, n: int) -> list[tuple[str, int, int]]:
    """n stocks priced ₹100–₹5,000 with expected returns of 5–60 %."""
    stocks = []
    for i in range(n):
        cost = rng.randint(100, 5000)
        value = int(cost * (1 + rng.uniform(0.05, 0.60)))
        stocks.append((f"S{i}", cost, value))
    return stocks


def quality_experiment(trials: int = 500, n: int = 5, budget: int = 20_000):
    rng = random.Random(SEED)
    gaps = []
    for _ in range(trials):
        stocks = random_universe(rng, n)
        g = greedy_allocation(stocks, budget).total_value
        d = dp_allocation(stocks, budget).total_value
        gaps.append((d - g) / d * 100 if d else 0.0)
    optimal_share = sum(gap == 0 for gap in gaps) / trials * 100
    return {
        "trials": trials, "n": n, "budget": budget,
        "greedy_optimal_pct": optimal_share,
        "mean_gap_pct": statistics.mean(gaps),
        "max_gap_pct": max(gaps),
    }


def runtime_experiment(budgets=(10_000, 50_000, 100_000, 250_000, 500_000), n: int = 5):
    rng = random.Random(SEED)
    stocks = random_universe(rng, n)
    rows = []
    for w in budgets:
        t0 = time.perf_counter(); greedy_allocation(stocks, w); tg = time.perf_counter() - t0
        t0 = time.perf_counter(); dp_allocation(stocks, w); td = time.perf_counter() - t0
        rows.append((w, tg, td))
    return rows


def main() -> None:
    RESULTS.mkdir(exist_ok=True)

    q = quality_experiment()
    rows = runtime_experiment()

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.plot([r[0] for r in rows], [r[2] for r in rows], "o-", label="Dynamic programming  O(n·W)")
    ax.plot([r[0] for r in rows], [r[1] for r in rows], "s-", label="Greedy  O(n log n)")
    ax.set_xlabel("Budget W (₹)")
    ax.set_ylabel("Runtime (s)")
    ax.set_title("Runtime vs budget (n = 5 stocks)")
    ax.grid(alpha=0.3)
    ax.legend()
    plt.tight_layout()
    plt.savefig(RESULTS / "runtime_vs_budget.png", dpi=120)
    plt.close()

    lines = [
        "# Benchmark results",
        "",
        f"Generated by `benchmarks/compare_algorithms.py` (seed {SEED}).",
        "",
        "## Solution quality",
        "",
        f"{q['trials']} random universes of {q['n']} stocks (₹100–₹5,000, 5–60 % expected return), "
        f"budget ₹{q['budget']:,}.",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Greedy found the optimum | {q['greedy_optimal_pct']:.1f} % of trials |",
        f"| Mean optimality gap | {q['mean_gap_pct']:.2f} % |",
        f"| Worst optimality gap | {q['max_gap_pct']:.2f} % |",
        "",
        "## Runtime",
        "",
        "| Budget W (₹) | Greedy (s) | DP (s) |",
        "|---|---|---|",
        *[f"| {w:,} | {tg:.6f} | {td:.3f} |" for w, tg, td in rows],
        "",
        "![Runtime vs budget](runtime_vs_budget.png)",
    ]
    (RESULTS / "benchmark_results.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
